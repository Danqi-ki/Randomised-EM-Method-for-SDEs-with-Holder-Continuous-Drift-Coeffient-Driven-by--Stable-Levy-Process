def LevyBase(T, M, N, alpha, beta=0, mu=0):
    """
    Generate M sample paths of 1D Lévy α-stable process over [0, T] with N steps.
    Returns:
        L: np.matrix of shape (M, N+1)
    """
    dt = float(T)/N #stepsize#
    scale = (dt/alpha) ** (1 / alpha)
    dL = levy_stable.rvs(alpha, beta, loc=mu, scale=scale, size=(M, N))
    L = np.matrix(np.insert(np.cumsum(dL, axis=1), 0, 0, axis=1))
    return L


def LevyCoarse(L, IntNum):
    """
    The levy generated by using the finest level of L

    Inputs:
        L: Lévy process sample paths, np.matrix of shape (M, N+1)
        IntNum: downsampling interval (e.g. 2, 4, 8...)

    Returns:
        The Levy is drived from the finest level
    """
    return L[:, ::IntNum]


    
def reduced_randomized_em_onestep(initial,stepsize,L,random_time_points,f,args_f):
    """

    To calculate randomized euler onestep forward according to Eqn. (RE-DDE)

    initial: initial evaluations, a vector of length the same as steps
    stepsize: scalar
    random_time_points: the random time points appearing in Eqn. (RE-SDE), a vector of length the same as initial

    """

    return  initial +stepsize * f(initial+ L, random_time_points,args_f)
    
def reduced_em_onestep(initial,stepsize,L,time_points,f,args_f):
    """

    To calculate euler onestep forward according to Eqn. (RE-DDE)

    initial: initial evaluations, a vector of length the same as steps
    stepsize: scalar
    time_points: time points appearing in Eqn. (RE-SDE), a vector of length the same as initial


    """

    return  initial +stepsize * f(initial+L,time_points,args_f)

def meanmax_error(sol,ref_sol,current_factor):
    """
    To calculate the average max error over each fixed iteration [j tau,(j+1)tau)

    input:
    sol, the evaluation from randomized euler scheme, with shape (steps, n_experiments)
    ref_sol, the reference solution, with shape (ref_steps, n_experiments)

    current_factor, the ratio of ref_steps to steps

    """

    return np.mean(np.nanmax(np.abs(sol[1:,:]-ref_sol[1::current_factor,:]),axis=0)**2)**(1/2)


