def error_plot_allinone( base_number, error_lists,time_factors_list, labels=["Randomised EM", "EM"],fontsize=14,savefig=False):


    linestyle_markers=['g-+','r-.x','b:^','k--o']

    for i in range(len(error_lists)):
      model = LinearRegression()
      x_prep=np.array(time_factors_list).reshape(-1, 1)
      y_prep=np.log10(error_lists[i]) if  base_number==10 else np.log2(error_lists[i])

      model.fit(x_prep, y_prep)

      print('Regression coefficient is ', -model.coef_[0])
      plt.plot(time_factors_list, error_lists[i], linestyle_markers[i+1], label=labels[i]+r" (slope %.2f)"%(-model.coef_[0]))


    plt.yscale('log')
    plt.ylabel('Error',fontsize=fontsize)
    plt.xlabel('Stepsize',fontsize=fontsize)
    plt.grid()
    plt.legend(fontsize=fontsize-1)
    plt.xticks(time_factors_list)

    if savefig:
          plt.savefig(savefig,dpi=300)
          plt.show()
    else:
          plt.show()











